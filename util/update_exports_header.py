#!/usr/bin/env python3
"""Regenerate include/workspace/exports.inc from EXPORTC definitions in qlogo/exports/exports*.cpp."""

import re
import subprocess
from pathlib import Path


def _repo_root() -> Path:
    result = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],
        capture_output=True,
        text=True,
        check=True,
        cwd=Path(__file__).resolve().parent,
    )
    return Path(result.stdout.strip())


REPO_ROOT = _repo_root()
HEADER_PATH = REPO_ROOT / "include" / "workspace" / "exports.inc"
SOURCE_GLOB = "qlogo/exports/exports*.cpp"

HEADER = """// DO NOT EDIT THIS FILE!
// Any changes to this file will not last long!
// It was generated by update_exports_header.py.
// See util/update_exports_header.py for details.
//
// Signature X-macro of EXPORTC definitions.
// Default: EXPORTC declarations. Define JIT_EXPORT(ret, name, params) before
// including this file to expand the list (ORC registration, FunctionTypes).

#ifndef JIT_EXPORT
#include "compiler_types.h"
#include "workspace/exports_internal.h"
#define JIT_EXPORT(ret, name, params) EXPORTC ret name params;
#define QLOGO_JIT_EXPORT_DEFAULT
#endif

"""

FOOTER = """
#ifdef QLOGO_JIT_EXPORT_DEFAULT
#undef JIT_EXPORT
#undef QLOGO_JIT_EXPORT_DEFAULT
#endif
"""

EXPORT_DEF_RE = re.compile(r"^EXPORTC\b(.*?)\s*([{;])", re.MULTILINE | re.DOTALL)


def normalize_signature(body: str) -> str:
    sig = "EXPORTC" + body
    if "//" in sig:
        sig = sig.split("//", 1)[0]
    return re.sub(r"[ \t]*\n[ \t]*", " ", sig).rstrip()


def parse_export_signature(normalized: str) -> tuple[str, str, str]:
    """Split 'EXPORTC ret name(params)' into (ret, name, params). params includes parens."""
    if not normalized.startswith("EXPORTC"):
        raise SystemExit(f"Could not parse EXPORTC signature:{normalized}")
    rest = normalized[len("EXPORTC") :].strip()
    idx = rest.find("(")
    if idx < 0:
        raise SystemExit(f"Could not parse EXPORTC parameters:{normalized}")
    head = rest[:idx].strip()
    params = rest[idx:].strip()
    parts = head.rsplit(None, 1)
    if len(parts) != 2:
        raise SystemExit(f"Could not parse EXPORTC name:{normalized}")
    return parts[0], parts[1], params


def extract_export_definitions(source_text: str) -> list[tuple[str, str, str]]:
    """EXPORTC definitions (signature followed by '{') as (ret, name, params)."""
    exports = []
    for match in EXPORT_DEF_RE.finditer(source_text):
        body, terminator = match.group(1), match.group(2)
        if terminator != "{":
            continue
        exports.append(parse_export_signature(normalize_signature(body)))
    return exports


def main() -> None:
    source_paths = sorted(REPO_ROOT.glob(SOURCE_GLOB))
    if not source_paths:
        raise SystemExit(f"No export sources matched {SOURCE_GLOB}")

    lines = [HEADER]
    seen = set()
    for source_path in source_paths:
        lines.append("\n")
        lines.append("//  -------------------------------------------------------------------\n")
        lines.append(f"//  {source_path.name}\n")
        lines.append("//  -------------------------------------------------------------------\n")
        lines.append("\n")
        source_text = source_path.read_text(encoding="utf-8")
        for ret, name, params in extract_export_definitions(source_text):
            if name in seen:
                continue
            seen.add(name)
            lines.append(f"JIT_EXPORT({ret}, {name}, {params})\n")

    lines.append(FOOTER)
    HEADER_PATH.write_text("".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
